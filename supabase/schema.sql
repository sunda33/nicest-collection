create table if not exists public.products (
  id bigint primary key,
  name text not null,
  category text not null check (category in ('shoes', 'bags', 'dresses', 'jewelry')),
  price bigint not null check (price >= 0),
  image text not null,
  tag text not null default '',
  position text not null default 'center',
  sizes text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'shipped', 'delivered', 'cancelled')),
  total bigint not null check (total >= 0),
  customer_name text not null,
  phone text not null,
  delivery_address text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_name text not null,
  unit_price bigint not null check (unit_price >= 0),
  quantity integer not null default 1 check (quantity > 0),
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

alter table public.products add column if not exists sizes text not null default '';
alter table public.products drop constraint if exists products_category_check;
alter table public.products add constraint products_category_check
  check (category in ('shoes', 'bags', 'dresses', 'jewelry'));

create policy "Public can view active products" on public.products
for select to anon, authenticated using (is_active = true);

create policy "Customers can create own orders" on public.orders
for insert to authenticated with check (false);

create policy "Customers can view own orders" on public.orders
for select to authenticated using (auth.uid() = user_id);

create policy "Customers can add items to own orders" on public.order_items
for insert to authenticated with check (false);

create policy "Customers can view own order items" on public.order_items
for select to authenticated using (
  exists (select 1 from public.orders where orders.id = order_items.order_id and orders.user_id = auth.uid())
);

