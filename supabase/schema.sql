create or replace function public.place_order(
  p_customer_name text,
  p_phone text,
  p_delivery_address text,
  p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_order_id uuid;
  v_total bigint;
  v_expected_items integer;
  v_valid_items integer;
begin
  if v_user_id is null then raise exception 'Authentication required'; end if;
  if nullif(trim(p_customer_name), '') is null
    or nullif(trim(p_phone), '') is null
    or nullif(trim(p_delivery_address), '') is null then
    raise exception 'Complete all delivery details';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your bag is empty';
  end if;

  with requested as (
    select product_id, quantity
    from jsonb_to_recordset(p_items) as item(product_id bigint, quantity integer)
  )
  select count(*)::integer, count(product.id)::integer,
    coalesce(sum(product.price * requested.quantity), 0)::bigint
  into v_expected_items, v_valid_items, v_total
  from requested
  left join public.products as product
    on product.id = requested.product_id and product.is_active = true
  where requested.quantity > 0;

  if v_expected_items = 0 or v_valid_items <> v_expected_items then
    raise exception 'One or more products are unavailable';
  end if;

  insert into public.orders (user_id, total, customer_name, phone, delivery_address)
  values (v_user_id, v_total, trim(p_customer_name), trim(p_phone), trim(p_delivery_address))
  returning id into v_order_id;

  insert into public.order_items (order_id, product_id, product_name, unit_price, quantity)
  select v_order_id, product.id, product.name, product.price, requested.quantity
  from jsonb_to_recordset(p_items) as requested(product_id bigint, quantity integer)
  join public.products as product
    on product.id = requested.product_id and product.is_active = true
  where requested.quantity > 0;

  return v_order_id;
end;
$$;

revoke all on function public.place_order(text, text, text, jsonb) from public;
grant execute on function public.place_order(text, text, text, jsonb) to authenticated;
